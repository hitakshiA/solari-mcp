// Copies the shared observers from solari-reflex into this package's dist, so the MCP
// server and the agent read pages and desktops identically.
//   node scripts/sync-observer.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

const reflex = new URL("../../solari-reflex/", import.meta.url);
const observer = readFileSync(new URL("dist/page/observer.js", reflex), "utf8");
const install = observer.match(/export function installObserver[\s\S]*?\n}\n/)?.[0];
const version = observer.match(/export const OBSERVER_VERSION = (\d+)/)?.[1];
if (!install || !version) throw new Error("could not find installObserver in reflex's build");
const fn = install.replace(/^export /, "");
const reflexd = gzipSync(readFileSync(new URL("src/desktop/reflexd.py", reflex)), { level: 9 }).toString("base64");
writeFileSync(new URL("../dist/observe-source.js", import.meta.url), `// Generated by scripts/sync-observer.mjs from solari-reflex. Do not edit.
export const OBSERVER_VERSION = ${version};
export const INSTALL_OBSERVER = ${JSON.stringify(`(${fn.trim()})(${version})`)};
export const REFLEXD_GZ_B64 = ${JSON.stringify(reflexd)};
`);
console.log("wrote dist/observe-source.js");
